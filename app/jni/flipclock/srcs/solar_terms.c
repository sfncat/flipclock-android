#define IX_XIAZHI 11 /* 夏至 */
#define IX_LIQIU 14  /* 立秋 */
#define IX_DONGZHI 23 /* 冬至 */

/* 儒略日数（格里历日历日），与 almanac_ref.py jdn() 同式。 */
static long _date_to_jdn(int year, int month, int day)
{
	int a = (14 - month) / 12;
	int y = year + 4800 - a;
	int m = month + 12 * a - 3;
	return (long)day + (153L * m + 2) / 5 + 365L * y + y / 4 - y / 100 +
	       y / 400 - 32045L;
}

/* 判断 (y,m,d) 是否合法公历日期。 */
static int _valid_date(int year, int month, int day)
{
	static const int dm[12] = { 31, 28, 31, 30, 31, 30,
				    31, 31, 30, 31, 30, 31 };
	if (year < SOLAR_TERMS_BASE_YEAR || year > SOLAR_TERMS_END_YEAR)
		return 0;
	if (month < 1 || month > 12)
		return 0;
	int mdays = dm[month - 1];
	if (month == 2 && ((year % 4 == 0 && year % 100 != 0) || year % 400 == 0))
		mdays = 29;
	return day >= 1 && day <= mdays;
}

/* 表内某年某节气（0..23）的公历日号；表外年份返回 0。 */
static int _term_day(int year, int idx)
{
	if (year < SOLAR_TERMS_BASE_YEAR || year > SOLAR_TERMS_END_YEAR)
		return 0;
	return SOLAR_TERMS_TABLE[year - SOLAR_TERMS_BASE_YEAR][idx];
}

/* 该年某节气（0..23）的儒略日；表外年份返回 0。 */
static long _term_jdn(int year, int idx)
{
	int day = _term_day(year, idx);
	if (day == 0)
		return 0;
	return _date_to_jdn(year, idx / 2 + 1, day);
}

/* 庚日：干支纪日天干为"庚"，等价 jdn % 10 == 7（0=甲子 对应 jdn 基点）。 */
static int _is_geng(long jdn)
{
	return (int)(jdn % 10L) == 7;
}

/* 从 start 起（含）第一个庚日的儒略日。 */
static long _first_geng_on_or_after(long start)
{
	while (!_is_geng(start))
		++start;
	return start;
}

/* 1..20 的日序汉字（中伏最长 20 天，数九最长 9 天）。 */
static const char *_cn_day(int n)
{
	static const char *const cn1[] = { "一", "二", "三", "四", "五",
					   "六", "七", "八", "九" };
	static const char *const cn10[] = { "十", "十一", "十二", "十三",
					    "十四", "十五", "十六", "十七",
					    "十八", "十九" };
	static const char *const cn20[] = { "二十" };
	if (n >= 1 && n <= 9)
		return cn1[n - 1];
	if (n >= 10 && n <= 19)
		return cn10[n - 10];
	if (n == 20)
		return cn20[0];
	return "";
}

/* 三伏段：0=初伏 1=中伏 2=末伏，每段 [start, end) 儒略日。 */
struct fu_segment {
	long start;
	long end;
};

/* 该年三伏区间；表外年份返回 0。 */
static int _fu_ranges(int year, struct fu_segment segs[3])
{
	long xia_zhi = _term_jdn(year, IX_XIAZHI);
	long li_qiu = _term_jdn(year, IX_LIQIU);
	if (xia_zhi == 0 || li_qiu == 0)
		return 0;
	/* 初伏 = 夏至后第 3 个庚日（首庚 + 20 天），10 天；
	   中伏 = 夏至后第 4 个庚日，长度 = 末伏起点 − 中伏起点（10 或 20 天）；
	   末伏 = 立秋后第 1 个庚日，10 天。 */
	long chu = _first_geng_on_or_after(xia_zhi) + 20;
	long zhong = chu + 10;
	long mo = _first_geng_on_or_after(li_qiu);
	segs[0].start = chu;
	segs[0].end = zhong;
	segs[1].start = zhong;
	segs[1].end = mo;
	segs[2].start = mo;
	segs[2].end = mo + 10;
	return 3;
}

const char *solar_term_of(int year, int month, int day)
{
	if (!_valid_date(year, month, day))
		return NULL;
	int i = (month - 1) * 2;
	int row = year - SOLAR_TERMS_BASE_YEAR;
	if (SOLAR_TERMS_TABLE[row][i] == day)
		return SOLAR_TERM_NAMES[i];
	if (SOLAR_TERMS_TABLE[row][i + 1] == day)
		return SOLAR_TERM_NAMES[i + 1];
	return NULL;
}

const char *solar_period_of(int year, int month, int day)
{
	if (!_valid_date(year, month, day))
		return NULL;
	long jdn = _date_to_jdn(year, month, day);

	/* 三伏（7-8 月） */
	struct fu_segment segs[3];
	if (_fu_ranges(year, segs) == 3) {
		static const char *const fu_names[3] = { "初伏", "中伏", "末伏" };
		for (int i = 0; i < 3; ++i) {
			if (jdn >= segs[i].start && jdn < segs[i].end) {
				int n = (int)(jdn - segs[i].start) + 1;
				static char buf[32];
				snprintf(buf, sizeof(buf), "%s第%s天",
					 fu_names[i], _cn_day(n));
				return buf;
			}
		}
	}

	/* 九九（12 月用当年冬至，1-3 月归上一年冬至） */
	if (month >= 4 && month <= 11)
		return NULL;
	int base_year = (month == 12) ? year : year - 1;
	long dong_zhi = _term_jdn(base_year, IX_DONGZHI);
	if (dong_zhi == 0)
		return NULL;
	long offset = jdn - dong_zhi;
	if (offset < 0 || offset >= 81)
		return NULL;
	static const char *const nine_names[9] = {
		"一", "二", "三", "四", "五", "六", "七", "八", "九"
	};
	static char buf[32];
	snprintf(buf, sizeof(buf), "%s九第%s天",
		 nine_names[(int)(offset / 9)], _cn_day((int)(offset % 9) + 1));
	return buf;
}

void solar_term_text_for(int year, int month, int day, char *buf,
			 size_t buf_size)
{
	if (buf == NULL || buf_size == 0)
		return;
	const char *term = solar_term_of(year, month, day);
	const char *period = solar_period_of(year, month, day);
	/* 节气与三伏/九九可同日出现（如大暑恰逢初伏），两者都显示。 */
	if (term != NULL && period != NULL) {
		snprintf(buf, buf_size, "%s %s", term, period);
	} else if (term != NULL) {
		snprintf(buf, buf_size, "%s", term);
	} else if (period != NULL) {
		snprintf(buf, buf_size, "%s", period);
	} else {
		buf[0] = '\0';
	}
}
